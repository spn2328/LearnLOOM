// Runs the Supabase migrations in an in-memory Postgres (PGlite) with a minimal stand-in for
// Supabase's auth schema and role grants, then checks Row Level Security as real roles.
// Covers access control only; it is not a substitute for a check against a real Supabase project.
import {PGlite} from "@electric-sql/pglite";
import {readFileSync, readdirSync} from "node:fs";
import assert from "node:assert/strict";

const db = new PGlite();
await db.exec(`
  create role anon nologin; create role authenticated nologin;
  create schema auth;
  create table auth.users (id uuid primary key, email text);
  create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  grant usage on schema auth to anon, authenticated;
  grant execute on function auth.uid() to anon, authenticated;
  grant usage on schema public to anon, authenticated;
  alter default privileges in schema public grant all on tables to anon, authenticated;
  alter default privileges in schema public grant execute on functions to anon, authenticated;
`);
const dir = new URL("../supabase/migrations/", import.meta.url);
for (const f of readdirSync(dir).filter(f => f.endsWith(".sql")).sort()) await db.exec(readFileSync(new URL(f, dir), "utf8"));

const ids = {t1: "11111111-1111-4111-8111-111111111111", t2: "22222222-2222-4222-8222-222222222222",
  s1: "33333333-3333-4333-8333-333333333333", s2: "44444444-4444-4444-8444-444444444444"};
for (const id of Object.values(ids)) await db.query("insert into auth.users (id) values ($1)", [id]);
await db.exec("insert into private.settings values ('teacher_code', 'TEST-CODE')");

let passed = 0;
async function as(who, sql, params = []) {
  await db.exec(who === "anon" ? "reset request.jwt.claim.sub; set role anon" : `set request.jwt.claim.sub = '${ids[who]}'; set role authenticated`);
  try { return (await db.query(sql, params)).rows; } finally { await db.exec("reset role; reset request.jwt.claim.sub"); }
}
async function ok(name, fn) { await fn(); passed++; console.log("✓", name); }
async function fails(name, fn) { let why = ""; await assert.rejects(fn, e => { why = e.message; return true; }, name); passed++; console.log("✓", name, `(${why})`); }

// Accounts and roles
await fails("cannot create own profile as teacher", () => as("s1", "insert into profiles (id, nickname, role) values ($1, 'ฟ้า', 'teacher')", [ids.s1]));
await fails("cannot create a profile for someone else", () => as("s1", "insert into profiles (id, nickname) values ($1, 'x')", [ids.s2]));
for (const [who, nick] of [["t1", "ครูเอ"], ["t2", "ครูบี"], ["s1", "ฟ้า"], ["s2", "ต้น"]])
  await as(who, "insert into profiles (id, nickname) values ($1, $2)", [ids[who], nick]);
await fails("student cannot set own role", () => as("s1", "update profiles set role = 'teacher' where id = $1", [ids.s1]));
await ok("student can change own nickname", async () => {
  await as("s1", "update profiles set nickname = 'ฟ้าใส' where id = $1", [ids.s1]);
  assert.equal((await as("s1", "select nickname from profiles where id = $1", [ids.s1]))[0].nickname, "ฟ้าใส");
});
await ok("wrong teacher code is refused", async () => assert.equal((await as("t1", "select claim_teacher('nope') r"))[0].r, false));
await ok("right teacher code grants teacher", async () => {
  assert.equal((await as("t1", "select claim_teacher('TEST-CODE') r"))[0].r, true);
  await as("t2", "select claim_teacher('TEST-CODE')");
});
await fails("anon cannot read private settings", () => as("anon", "select * from private.settings"));
await fails("student cannot read private settings", () => as("s1", "select * from private.settings"));

// Classes
await fails("student cannot create a class", () => as("s1", "insert into classrooms (teacher_id, name) values ($1, 'x')", [ids.s1]));
const [c1] = await as("t1", "insert into classrooms (teacher_id, name, join_code) values ($1, 'ม.6/1', 'MINE') returning id, join_code", [ids.t1]);
const [c2] = await as("t2", "insert into classrooms (teacher_id, name) values ($1, 'ม.6/2') returning id, join_code", [ids.t2]);
await ok("join code is generated by the server", async () => assert.match(c1.join_code, /^[0-9A-F]{6}$/));
await ok("teacher cannot overwrite the join code", async () => {
  await as("t1", "update classrooms set join_code = 'AAAAAA', name = 'ม.6/1 เคมี' where id = $1", [c1.id]);
  const [r] = await as("t1", "select join_code, name from classrooms where id = $1", [c1.id]);
  assert.equal(r.join_code, c1.join_code); assert.equal(r.name, "ม.6/1 เคมี");
});
await ok("teacher cannot see another teacher's class", async () => assert.equal((await as("t1", "select id from classrooms where id = $1", [c2.id])).length, 0));
await ok("wrong join code joins nothing", async () => assert.equal((await as("s1", "select join_class('ZZZZZZ') r"))[0].r, null));
await as("s1", "select join_class($1)", [c1.join_code.toLowerCase()]);
await as("s2", "select join_class($1)", [c2.join_code]);
await fails("teacher cannot join a class as student", () => as("t2", "select join_class($1)", [c1.join_code]));
await ok("student sees only the class they joined", async () => {
  const rows = await as("s1", "select id from classrooms");
  assert.deepEqual(rows.map(r => r.id), [c1.id]);
});

// Attempts and answers
const a1 = "aaaaaaaa-0000-4000-8000-000000000001", a1b = "aaaaaaaa-0000-4000-8000-000000000002", a2 = "bbbbbbbb-0000-4000-8000-000000000001";
await as("s1", "insert into attempts (id, user_id, episode, number, started_at) values ($1, $2, 'EP01', 1, now())", [a1, ids.s1]);
await as("s2", "insert into attempts (id, user_id, episode, number, started_at) values ($1, $2, 'EP01', 1, now())", [a2, ids.s2]);
const ev = (id, attempt, user, value) => ["insert into answer_events (id, attempt_id, user_id, concept, item_id, kind, value, correct, recorded_at) values ($1, $2, $3, 'C01', 'Q01', 'main', $4, true, now()) on conflict do nothing", [id, attempt, user, value]];
await as("s1", ...ev("ev-s1-q01-A", a1, ids.s1, "A"));
await ok("re-sending the same event is a no-op", async () => {
  await as("s1", ...ev("ev-s1-q01-A", a1, ids.s1, "A"));
  assert.equal((await as("s1", "select count(*)::int n from answer_events"))[0].n, 1);
});
await fails("cannot write an answer for another student", () => as("s1", ...ev("ev-fake-0001", a2, ids.s2, "B")));
await fails("cannot attach an answer to another student's attempt", () => as("s1", ...ev("ev-fake-0002", a2, ids.s1, "B")));
await ok("answers cannot be edited or deleted", async () => {
  await as("s1", "update answer_events set value = 'D'").catch(() => {});
  await as("s1", "delete from answer_events").catch(() => {});
  const [r] = await as("s1", "select value from answer_events where id = 'ev-s1-q01-A'");
  assert.equal(r.value, "A");
});
await ok("a retake is a separate attempt; the first stays", async () => {
  await as("s1", "insert into attempts (id, user_id, episode, number, started_at) values ($1, $2, 'EP01', 2, now())", [a1b, ids.s1]);
  await as("s1", ...ev("ev-s1-q01-B-2", a1b, ids.s1, "B"));
  const rows = await as("s1", "select a.number, e.value from answer_events e join attempts a on a.id = e.attempt_id order by a.number");
  assert.deepEqual(rows.map(r => [r.number, r.value]), [[1, "A"], [2, "B"]]);
});
await fails("attempt number cannot be rewritten", () => as("s1", "update attempts set number = 9 where id = $1", [a1]));

// Who can read what
await ok("student cannot read a classmate's answers", async () => assert.equal((await as("s2", "select * from answer_events where user_id = $1", [ids.s1])).length, 0));
await ok("teacher reads answers of students in own class", async () => assert.equal((await as("t1", "select * from answer_events where user_id = $1", [ids.s1])).length, 2));
await ok("teacher cannot read students of another class", async () => {
  assert.equal((await as("t2", "select * from answer_events where user_id = $1", [ids.s1])).length, 0);
  assert.equal((await as("t1", "select * from profiles where id = $1", [ids.s2])).length, 0);
});
await ok("anon reads nothing", async () => {
  for (const t of ["profiles", "classrooms", "answer_events", "attempts"]) await assert.rejects(() => as("anon", `select * from ${t}`));
});
await as("s1", "insert into progress_snapshots (user_id, episode, data) values ($1, 'EP01', '{\"k\":1}')", [ids.s1]);
await ok("snapshot is private even from the teacher", async () => assert.equal((await as("t1", "select * from progress_snapshots")).length, 0));
await as("s1", "insert into concept_results (attempt_id, user_id, concept, outcome, path) values ($1, $2, 'C01', 'ยังต้องทบทวน', 'B')", [a1, ids.s1]);
await ok("concept route can be updated by its owner (upsert)", async () => {
  await as("s1", "insert into concept_results (attempt_id, user_id, concept, outcome, path) values ($1, $2, 'C01', 'ผ่านหลังช่วยเหลือ', 'B') on conflict (attempt_id, concept) do update set outcome = excluded.outcome", [a1, ids.s1]);
  assert.equal((await as("s1", "select outcome from concept_results"))[0].outcome, "ผ่านหลังช่วยเหลือ");
  await as("s2", "update concept_results set outcome = 'x'");
  assert.equal((await as("s1", "select outcome from concept_results"))[0].outcome, "ผ่านหลังช่วยเหลือ");
});
await ok("teacher sees concept routes of own students only", async () => {
  assert.equal((await as("t1", "select * from concept_results")).length, 1);
  assert.equal((await as("t2", "select * from concept_results")).length, 0);
});

console.log(`\n${passed} database access checks passed`);

// Event ids from the browser sync are stable, so re-sending the outbox never duplicates history.
const {eventsFrom, stableId} = await import("../features/fake-hero/cloud/records.ts");
const sample = {concepts: [{id: "C01", firstMain: "A", firstReason: "B", firstCorrect: false, assisted: true, recheckCorrect: false, outcome: "ยังต้องทบทวน",
  diagnosis: {"D01-1": "A"}, practice: {"R01-1": "C"}, practiceRetry: {"R01-1": "A"}, recheck: "B"}], checkpoint: {answers: {CP01: "A"}, reasons: {}}, transfer: ""};
const keys = {main: {Q01: "A"}, reason: {Q01: "A"}, checkpoint: {CP01: "A"}, checkpointReason: {}};
await ok("same answers → same event ids (idempotent re-send)", async () => {
  const x = eventsFrom(sample, keys, a1, ids.s1, "2026-11-03T00:00:00Z"), y = eventsFrom(sample, keys, a1, ids.s1, "2026-11-04T00:00:00Z");
  assert.deepEqual(x.map(e => e.id), y.map(e => e.id));
  assert.equal(new Set(x.map(e => e.id)).size, x.length);
  assert.deepEqual(x.map(e => e.kind), ["main", "reason", "diagnosis", "practice", "practice_retry", "recheck", "checkpoint"]);
  assert.deepEqual(x.slice(0, 2).map(e => e.correct), [true, false]);
});
await ok("a retake gets different event ids", async () => {
  const x = eventsFrom(sample, keys, a1, ids.s1, "t"), y = eventsFrom(sample, keys, a1b, ids.s1, "t");
  assert.equal(x.filter(e => y.some(f => f.id === e.id)).length, 0);
  assert.notEqual(stableId("a"), stableId("b"));
});
await ok("synced rows insert once even when sent twice", async () => {
  const rows = eventsFrom(sample, keys, a1b, ids.s1, new Date().toISOString());
  for (let round = 0; round < 2; round++) for (const e of rows)
    await as("s1", "insert into answer_events (id, attempt_id, user_id, concept, item_id, kind, value, correct, recorded_at) values ($1,$2,$3,$4,$5,$6,$7,$8,$9) on conflict do nothing",
      [e.id, e.attempt_id, e.user_id, e.concept, e.item_id, e.kind, e.value, e.correct, e.recorded_at]);
  assert.equal((await as("s1", "select count(*)::int n from answer_events where attempt_id = $1", [a1b]))[0].n, rows.length + 1);
});
console.log(`${passed} checks passed in total`);
